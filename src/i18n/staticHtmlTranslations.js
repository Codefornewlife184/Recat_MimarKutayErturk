const EASTERN_ARABIC_DIGITS = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩']

function convertToEasternArabicDigits(str) {
  return String(str).replace(/[0-9]/g, (digit) => EASTERN_ARABIC_DIGITS[digit])
}

function encodeAlphabeticIndex(value) {
  let n = Number(value) || 0
  let output = ''
  do {
    output = String.fromCharCode(97 + (n % 26)) + output
    n = Math.floor(n / 26) - 1
  } while (n >= 0)
  return output
}

function maskUnsafeAttributeValues(html) {
  const attributeMap = new Map()
  const maskedHtml = String(html || '').replace(
    /\b(src|href|data-background|srcset|poster)\s*=\s*(["'])([\s\S]*?)\2/gi,
    (_, attrName, quote, value) => {
      const token = `__ATTR_${encodeAlphabeticIndex(attributeMap.size)}__`
      attributeMap.set(token, value)
      return `${attrName}=${quote}${token}${quote}`
    },
  )

  return {
    maskedHtml,
    restore: (value) => String(value || '').replace(/__ATTR_[a-z]+__/g, (token) => attributeMap.get(token) ?? token),
  }
}

export function translateStaticHtml(pageKey, html, locale = 'tr') {
  const effectivePageKey = pageKey === 'aboutus' ? 'about' : pageKey
  const replacements = staticHtmlTranslations[effectivePageKey]?.[locale]
  if (!replacements?.length) return html

  const { maskedHtml, restore } = maskUnsafeAttributeValues(html)
  const sortedReplacements = [...replacements].sort(
    ([aSource], [bSource]) => String(bSource || '').length - String(aSource || '').length,
  )
  let output = sortedReplacements.reduce((result, [source, target]) => result.replaceAll(source, target), maskedHtml)

  if (locale === 'ar') {
    // Disable standard odometer for Arabic by renaming the class
    output = output.replace(/class="([^"]*)\bodometer\b([^"]*)"/g, 'class="$1odometer-ar$2"')

    // Only replace numbers that are outside of HTML tags to avoid breaking attributes (src, class, etc.)
    output = output.replace(/(<[^>]+>)|([0-9]+)/g, (match, tag, number) => {
      if (tag) return tag
      return convertToEasternArabicDigits(number)
    })
  }

  if (effectivePageKey === 'contact' && locale !== 'tr') {
    const contactBadgeByLocale = {
      en: 'Contact Us!',
      ar: 'تواصل معنا!',
    }
    const contactHeadingByLocale = {
      en: 'Do You Have A Project In Mind?<span>Let us\n                        </span> <br>bring it to life together!',
      ar: 'هل لديك مشروع في ذهنك؟<span>دعنا\n                        </span> <br>نحوّله إلى واقع معاً!',
    }

    output = output.replaceAll('Bize Ulaşın!', contactBadgeByLocale[locale] || 'Bize Ulaşın!')
    output = output.replace(
      /Aklınızda Bir Proje mi Var \?<span>\s*Hadi birlikte\s*<\/span>\s*<br>\s*gerçekleştirelim !/gi,
      contactHeadingByLocale[locale] || 'Aklınızda Bir Proje mi Var ?<span>Hadi birlikte\n                        </span> <br>gerçekleştirelim !',
    )
  }

  return restore(output)
}
